#!/usr/bin/env node
// Generates knowledge-base-content.md from intake-form.json
// Output: output/knowledge-base-content.md
// Push all detailed reference content here — keep the system prompt under 2,000 words.

const fs = require('fs');
const path = require('path');

const intakePath = process.argv[2] || path.join(__dirname, 'intake-form.json');
const outputDir = path.join(__dirname, 'output');

function load(filePath) {
  if (!fs.existsSync(filePath)) {
    console.error(`ERROR: Intake form not found at ${filePath}`);
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function formatHours(hours) {
  const days = ['monday','tuesday','wednesday','thursday','friday','saturday','sunday'];
  return days.map(d => {
    const h = hours[d];
    if (!h || h.open === 'closed') return `| ${capitalize(d)} | Closed |`;
    return `| ${capitalize(d)} | ${h.open} – ${h.close} |`;
  }).join('\n');
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function generate(intake) {
  const serviceRows = intake.services.map(s => `| ${s} | See technician for details |`).join('\n');
  const cityList = intake.service_areas.cities.join(', ');
  const zipTable = intake.service_areas.zip_codes.map(z => `- ${z}`).join('\n');
  const faqSection = intake.faqs.map(f => `**Q: ${f.question}**\n\nA: ${f.answer}`).join('\n\n---\n\n');
  const mainPlan = intake.maintenance_plan_name || 'Maintenance Plan';
  const mainPrice = intake.maintenance_plan_price || 'Contact us for pricing';

  return `# ${intake.business_name} — Knowledge Base Content

> **GHL Setup Note:** Paste the contents of this document into the Knowledge Base for the ${intake.agent_name} Voice AI agent.
> After saving, wait **1–2 minutes** before testing — Knowledge Base content propagation is not instant.

---

## 1. Services Offered

| Service | Notes |
|---|---|
${serviceRows}

---

## 2. Pricing Policy

${intake.pricing_policy}

> **Agent instruction:** Do not quote specific prices not listed above. Direct pricing questions to the technician or the human handoff line.

---

## 3. Service Area Coverage

**Serving the following cities:**
${cityList}

**ZIP codes covered:**
${zipTable}

Callers outside these areas should be politely declined and advised to find a local provider. Do not book appointments outside the service area.

---

## 4. Operating Hours

| Day | Hours |
|---|---|
${formatHours(intake.operating_hours)}

**Timezone:** ${intake.operating_hours.timezone}

Emergency service is available 24/7 per the emergency policy below.

---

## 5. Frequently Asked Questions

${faqSection}

---

## 6. Emergency Policy

${intake.emergency_policy}

---

## 7. Maintenance / Service Plan

**Plan Name:** ${mainPlan}
**Price:** ${mainPrice}

Plan benefits:
- Two annual HVAC tune-ups (spring and fall)
- Priority scheduling — plan members move to the front of the queue
- 15% discount on all repair services
- No diagnostic fees for plan members

> **Seasonal promotions placeholder:** Add current promotions here before each season. Remove expired promotions promptly.

---

## 8. Warranty Information

- **Labor warranty:** 1 year on all installations and replacements
- **Parts warranty:** Manufacturer warranty applies (typically 5–10 years depending on brand and model)
- Warranty is void if the system is serviced by an unlicensed technician after installation

> **Note:** Update this section if warranty terms change or manufacturer warranty programs are updated.

---

## 9. Seasonal Promotions

> **Placeholder — update before each season:**
>
> Example: "Spring AC Tune-Up Special — $59 (reg. $89) through May 31."
>
> Remove expired promotions before testing the agent. Outdated promotions in the Knowledge Base will be quoted by the agent.

---

*Last updated: ${new Date().toISOString().split('T')[0]}*
*Generated by WebGuildAI GHL Agent Setup Framework*
`;
}

const intake = load(intakePath);
const content = generate(intake);

if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir, { recursive: true });
const outPath = path.join(outputDir, 'knowledge-base-content.md');
fs.writeFileSync(outPath, content, 'utf8');
console.log(`✓ knowledge-base-content.md → ${outPath}`);
